  for select to authenticated
  using (
    (
      portee = 'entreprise'
      and public.acces_finance_entreprise(owner_id)
      and (
        public.peut('rapports', 'voir') or public.peut('finance', 'voir')
        or public.peut('caisse', 'voir') or public.peut('depenses', 'voir')
        or public.peut('stock', 'voir')
      )
    )
    or (
      portee = 'plateforme'
      and public.est_plateforme()
    )
  );


