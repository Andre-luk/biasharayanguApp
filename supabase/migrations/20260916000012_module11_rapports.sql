-- ============================================================================
--  4. `rpc_rapport_plateforme` — RAPPORTS LA PERLE
-- ============================================================================
--  Types acceptés (p_type) :
--    • 'revenus'             — revenus globaux par mois (les 2 historiques de
--                              paiements : `paiements_abonnement` (Module 1)
--                              et `paiements_abonnements_laperle` (Module 3)) ;
--    • 'abonnements_actifs'  — répartition par statut d'abonnement ;
--    • 'impayes'             — entreprises avec solde restant dû ;
--    • 'villes'              — revenus par ville ;
--    • 'activites'           — revenus par activité ;
--    • 'nouveaux_comptes'    — entreprises + utilisateurs créés par période.
--
--  Droits :
--    revenus / impayes / villes / activites → finance/voir ou paiements/voir ;
--    abonnements_actifs → abonnements/voir ou rapports/voir ;
--    nouveaux_comptes   → entreprises/voir ou rapports/voir.
--  Réservé au personnel de la plateforme (`est_plateforme()`).
--
--  Codes d'erreur : SESSION_ABSENTE | ACCES_REFUSE | DROIT_REFUSE |
--                   TYPE_INVALIDE | GROUPE_INVALIDE | PERIODE_INVALIDE

create or replace function public.rpc_rapport_plateforme(
  p_type    text,
  p_debut   date default null,
  p_fin     date default null,
  p_filtres jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user       uuid := auth.uid();
  v_type       text := lower(btrim(coalesce(p_type, '')));
  v_filtres    jsonb := coalesce(p_filtres, '{}'::jsonb);
  v_debut      date;
  v_fin        date;
  v_d0         timestamptz;
  v_d1         timestamptz;
  v_groupe     text;
  v_titre      text := 'Rapport plateforme';
  v_colonnes   jsonb := '[]'::jsonb;
  v_lignes     jsonb := '[]'::jsonb;
  v_totaux     jsonb := '{}'::jsonb;
  v_resume     jsonb := '[]'::jsonb;
  v_parametres jsonb := '{}'::jsonb;
  v_nb         integer := 0;
  v_total      numeric := 0;
  v_paye       numeric := 0;
  v_solde      numeric := 0;
  v_encaisse   numeric := 0;
  v_retard     integer := 0;
begin
  if v_user is null then
    raise exception 'SESSION_ABSENTE|Connectez-vous pour générer un rapport.';
  end if;

  if not public.est_plateforme() then
    raise exception 'ACCES_REFUSE|Ces rapports sont réservés au personnel de la plateforme.';
  end if;

  -- Contrôle des droits selon le type (avant tout calcul).
  if v_type in ('revenus', 'impayes', 'villes', 'activites') then
    if not (public.peut('finance', 'voir') or public.peut('paiements', 'voir')) then
      raise exception 'DROIT_REFUSE|Votre rôle ne permet pas de consulter les données financières de la plateforme.';
    end if;
  elsif v_type = 'abonnements_actifs' then
    if not (public.peut('abonnements', 'voir') or public.peut('rapports', 'voir')) then
      raise exception 'DROIT_REFUSE|Votre rôle ne permet pas de consulter les abonnements.';
    end if;
  elsif v_type = 'nouveaux_comptes' then
    if not (public.peut('entreprises', 'voir') or public.peut('rapports', 'voir')) then
      raise exception 'DROIT_REFUSE|Votre rôle ne permet pas de consulter les entreprises.';
    end if;
  else
    raise exception 'TYPE_INVALIDE|Type de rapport plateforme inconnu : « % ».', v_type;
  end if;

  v_debut := coalesce(p_debut, current_date - 29);
  v_fin   := coalesce(p_fin, current_date);

  if v_debut > v_fin then
    raise exception 'PERIODE_INVALIDE|La date de début doit précéder la date de fin.';
  end if;
  if (v_fin - v_debut) > 366 then
    raise exception 'PERIODE_INVALIDE|Période trop longue : 366 jours maximum.';
  end if;

  v_d0 := v_debut::timestamptz;
  v_d1 := (v_fin + 1)::timestamptz;

  case v_type

  -- ==================================================================== revenus
  when 'revenus' then
    v_titre := 'Revenus globaux de la plateforme';

    with pa as (
      select date_trunc('month', p.created_at)::date as mois,
             p.montant,
             null::text as type_paiement
        from public.paiements_abonnement p
       where p.created_at >= v_d0 and p.created_at < v_d1
      union all
      select date_trunc('month', q.created_at)::date,
             q.montant,
             upper(btrim(coalesce(q.type_paiement, '')))
        from public.paiements_abonnements_laperle q
       where q.created_at >= v_d0 and q.created_at < v_d1
    ),
    agg as (
      select mois,
             count(*) as nb,
             coalesce(sum(montant) filter (where type_paiement = 'AVANCE'), 0) as avances,
             coalesce(sum(montant) filter (where type_paiement = 'SOLDE'), 0) as soldes,
             coalesce(sum(montant) filter (where type_paiement = 'RENOUVELLEMENT'), 0) as renouvellements,
             coalesce(sum(montant) filter (
               where type_paiement is null
                  or type_paiement not in ('AVANCE', 'SOLDE', 'RENOUVELLEMENT')), 0) as autres,
             coalesce(sum(montant), 0) as total
        from pa
       group by 1
    )
    select coalesce(jsonb_agg(jsonb_build_object(
             'mois',           to_char(a.mois, 'MM/YYYY'),
             'nb_paiements',   a.nb,
             'avances',        a.avances,
             'soldes',         a.soldes,
             'renouvellements', a.renouvellements,
             'autres',         a.autres,
             'montant_total',  a.total
           ) order by a.mois), '[]'::jsonb)
      into v_lignes
      from agg a;

    v_colonnes := jsonb_build_array(
      jsonb_build_object('cle', 'mois',            'libelle', 'Mois',            'type', 'texte'),
      jsonb_build_object('cle', 'nb_paiements',    'libelle', 'Paiements',       'type', 'nombre'),
      jsonb_build_object('cle', 'avances',         'libelle', 'Avances',         'type', 'montant'),
      jsonb_build_object('cle', 'soldes',          'libelle', 'Soldes',          'type', 'montant'),
      jsonb_build_object('cle', 'renouvellements', 'libelle', 'Renouvellements', 'type', 'montant'),
      jsonb_build_object('cle', 'autres',          'libelle', 'Autres',          'type', 'montant'),
      jsonb_build_object('cle', 'montant_total',   'libelle', 'Total',           'type', 'montant')
    );

    select coalesce(sum(montant), 0), count(*)
      into v_encaisse, v_nb
      from (
        select p.montant from public.paiements_abonnement p
         where p.created_at >= v_d0 and p.created_at < v_d1
        union all
        select q.montant from public.paiements_abonnements_laperle q
         where q.created_at >= v_d0 and q.created_at < v_d1
      ) t;

    select coalesce(sum(q.montant), 0)
      into v_total
      from public.paiements_abonnements_laperle q
     where q.created_at >= date_trunc('month', current_date)
       and q.created_at < date_trunc('month', current_date) + interval '1 month';

    v_totaux := jsonb_build_object('montant_total', coalesce(v_encaisse, 0), 'nb_paiements', coalesce(v_nb, 0));
    v_resume := jsonb_build_array(
      jsonb_build_object('libelle', 'Revenus de la période', 'valeur', coalesce(v_encaisse, 0), 'type', 'montant'),
      jsonb_build_object('libelle', 'Paiements',             'valeur', coalesce(v_nb, 0),       'type', 'nombre'),
      jsonb_build_object('libelle', 'Revenus du mois en cours', 'valeur', coalesce(v_total, 0),  'type', 'montant')
    );

  -- ======================================================== abonnements_actifs
  when 'abonnements_actifs' then
    v_titre := 'Abonnements par statut';

    with agg as (
      select upper(coalesce(e.statut::text, 'INCONNU')) as statut,
             count(*) as nb,
             coalesce(sum(e.montant_total_du), 0) as total_du,
             coalesce(sum(e.montant_deja_paye), 0) as paye,
             coalesce(sum(coalesce(e.solde_restant,
                          greatest(coalesce(e.montant_total_du, 0) - coalesce(e.montant_deja_paye, 0), 0))), 0) as solde
        from public.entreprises e
       group by 1
    )
    select coalesce(jsonb_agg(jsonb_build_object(
             'statut',       a.statut,
             'nb',           a.nb,
             'montant_total', a.total_du,
             'montant_paye', a.paye,
             'solde',        a.solde
           ) order by a.nb desc, a.statut), '[]'::jsonb)
      into v_lignes
      from agg a;

    v_colonnes := jsonb_build_array(
      jsonb_build_object('cle', 'statut',        'libelle', 'Statut',        'type', 'texte'),
      jsonb_build_object('cle', 'nb',            'libelle', 'Entreprises',   'type', 'nombre'),
      jsonb_build_object('cle', 'montant_total', 'libelle', 'Montant dû',    'type', 'montant'),
      jsonb_build_object('cle', 'montant_paye',  'libelle', 'Déjà payé',     'type', 'montant'),
      jsonb_build_object('cle', 'solde',         'libelle', 'Solde restant', 'type', 'montant')
    );

    select count(*),
           count(*) filter (where upper(e.statut::text) in ('ACTIF', 'ESSAI_7J')),
           count(*) filter (where upper(e.statut::text) = 'EXPIRE'),
           count(*) filter (where upper(e.statut::text) = 'SUSPENDU'),
           coalesce(sum(coalesce(e.solde_restant,
                    greatest(coalesce(e.montant_total_du, 0) - coalesce(e.montant_deja_paye, 0), 0))), 0)
      into v_nb, v_encaisse, v_total, v_paye, v_solde
      from public.entreprises e;

    v_totaux := jsonb_build_object(
      'nb',            v_nb,
      'nb_actifs',     v_encaisse,
      'nb_expires',    v_total,
      'nb_suspendus',  v_paye,
      'solde_total',   v_solde
    );
    v_resume := jsonb_build_array(
      jsonb_build_object('libelle', 'Entreprises',   'valeur', v_nb,        'type', 'nombre'),
      jsonb_build_object('libelle', 'Actives',       'valeur', v_encaisse,  'type', 'nombre'),
      jsonb_build_object('libelle', 'Expirées',      'valeur', v_total,     'type', 'nombre'),
      jsonb_build_object('libelle', 'Solde restant', 'valeur', v_solde,     'type', 'montant')
    );

  -- =================================================================== impayes
  when 'impayes' then
    v_titre := 'Impayés (soldes restants dus)';

    with base as (
      select e.nom as entreprise,
             coalesce(v.nom, 'Non renseignée') as ville,
             upper(coalesce(e.statut::text, 'INCONNU')) as statut,
             coalesce(e.montant_total_du, 0) as total_du,
             coalesce(e.montant_deja_paye, 0) as paye,
             coalesce(e.solde_restant,
                      greatest(coalesce(e.montant_total_du, 0) - coalesce(e.montant_deja_paye, 0), 0)) as solde,
             e.date_expiration
        from public.entreprises e
        left join public.villes v on v.id = e.ville_id
       where coalesce(e.solde_restant,
               greatest(coalesce(e.montant_total_du, 0) - coalesce(e.montant_deja_paye, 0), 0)) > 0
       order by solde desc
       limit 500
    )
    select coalesce(jsonb_agg(jsonb_build_object(
             'entreprise',  b.entreprise,
             'ville',       b.ville,
             'statut',      b.statut,
             'montant_total', b.total_du,
             'montant_paye', b.paye,
             'solde',       b.solde,
             'expiration',  case when b.date_expiration is null then null
                                 else to_char(b.date_expiration, 'DD/MM/YYYY') end,
             'jours_retard', case when b.date_expiration is null then null
                                  else greatest(current_date - b.date_expiration::date, 0) end
           )), '[]'::jsonb)
      into v_lignes
      from base b;

    v_colonnes := jsonb_build_array(
      jsonb_build_object('cle', 'entreprise',   'libelle', 'Entreprise',    'type', 'texte'),
      jsonb_build_object('cle', 'ville',        'libelle', 'Ville',         'type', 'texte'),
      jsonb_build_object('cle', 'statut',       'libelle', 'Statut',        'type', 'texte'),
      jsonb_build_object('cle', 'montant_total', 'libelle', 'Montant dû',   'type', 'montant'),
      jsonb_build_object('cle', 'montant_paye', 'libelle', 'Déjà payé',     'type', 'montant'),
      jsonb_build_object('cle', 'solde',        'libelle', 'Solde restant', 'type', 'montant'),
      jsonb_build_object('cle', 'expiration',   'libelle', 'Expiration',    'type', 'texte'),
      jsonb_build_object('cle', 'jours_retard', 'libelle', 'Retard (j)',    'type', 'nombre')
    );

    select count(*),
           coalesce(sum(coalesce(e.solde_restant,
             greatest(coalesce(e.montant_total_du, 0) - coalesce(e.montant_deja_paye, 0), 0))), 0),
           count(*) filter (
             where e.date_expiration is not null
               and e.date_expiration < current_date
           )
      into v_nb, v_solde, v_retard
      from public.entreprises e
     where coalesce(e.solde_restant,
             greatest(coalesce(e.montant_total_du, 0) - coalesce(e.montant_deja_paye, 0), 0)) > 0;

    v_totaux := jsonb_build_object('nb', v_nb, 'solde_total', v_solde, 'nb_en_retard', v_retard);
    v_resume := jsonb_build_array(
      jsonb_build_object('libelle', 'Entreprises en impayé', 'valeur', v_nb,     'type', 'nombre'),
      jsonb_build_object('libelle', 'Solde restant total',   'valeur', v_solde,  'type', 'montant'),
      jsonb_build_object('libelle', 'En retard',             'valeur', v_retard, 'type', 'nombre')
    );

  -- ==================================================================== villes
  when 'villes' then
    v_titre := 'Revenus par ville';

    with agg as (
      select coalesce(v.nom, 'Non renseignée') as ville,
             count(*) as nb,
             coalesce(sum(e.montant_total_du), 0) as total_du,
             coalesce(sum(e.montant_deja_paye), 0) as paye,
             coalesce(sum(coalesce(e.solde_restant,
               greatest(coalesce(e.montant_total_du, 0) - coalesce(e.montant_deja_paye, 0), 0))), 0) as solde
        from public.entreprises e
        left join public.villes v on v.id = e.ville_id
       group by 1
    )
    select coalesce(jsonb_agg(jsonb_build_object(
             'ville',         a.ville,
             'nb_entreprises', a.nb,
             'montant_total', a.total_du,
             'montant_paye',  a.paye,
             'solde',         a.solde,
             'taux',          coalesce(round(100.0 * a.paye / nullif(a.total_du, 0), 1), 0)
           ) order by a.total_du desc, a.ville), '[]'::jsonb)
      into v_lignes
      from agg a;

    v_colonnes := jsonb_build_array(
      jsonb_build_object('cle', 'ville',          'libelle', 'Ville',           'type', 'texte'),
      jsonb_build_object('cle', 'nb_entreprises', 'libelle', 'Entreprises',     'type', 'nombre'),
      jsonb_build_object('cle', 'montant_total',  'libelle', 'Montant dû',      'type', 'montant'),
      jsonb_build_object('cle', 'montant_paye',   'libelle', 'Encaissé',        'type', 'montant'),
      jsonb_build_object('cle', 'solde',          'libelle', 'Solde restant',   'type', 'montant'),
      jsonb_build_object('cle', 'taux',           'libelle', 'Recouvrement',    'type', 'pourcentage')
    );

    select count(*), coalesce(sum(e.montant_total_du), 0), coalesce(sum(e.montant_deja_paye), 0)
      into v_nb, v_total, v_paye
      from public.entreprises e;

    v_totaux := jsonb_build_object(
      'nb_entreprises', v_nb,
      'montant_total',  v_total,
      'montant_paye',   v_paye,
      'solde',          greatest(v_total - v_paye, 0)
    );
    v_resume := jsonb_build_array(
      jsonb_build_object('libelle', 'Entreprises', 'valeur', v_nb,                              'type', 'nombre'),
      jsonb_build_object('libelle', 'Montant dû',  'valeur', v_total,                           'type', 'montant'),
      jsonb_build_object('libelle', 'Encaissé',    'valeur', v_paye,                            'type', 'montant'),
      jsonb_build_object('libelle', 'Solde',       'valeur', greatest(v_total - v_paye, 0),     'type', 'montant')
    );

  -- ================================================================== activites
  when 'activites' then
    v_titre := 'Revenus par activité';

    with agg as (
      select coalesce(a2.nom, 'Non renseignée') as activite,
             count(*) as nb,
             coalesce(sum(e.montant_total_du), 0) as total_du,
             coalesce(sum(e.montant_deja_paye), 0) as paye,
             coalesce(sum(coalesce(e.solde_restant,
               greatest(coalesce(e.montant_total_du, 0) - coalesce(e.montant_deja_paye, 0), 0))), 0) as solde
        from public.entreprises e
        left join public.activites a2 on a2.id = e.activite_id
       group by 1
    )
    select coalesce(jsonb_agg(jsonb_build_object(
             'activite',      a.activite,
             'nb_entreprises', a.nb,
             'montant_total', a.total_du,
             'montant_paye',  a.paye,
             'solde',         a.solde,
             'taux',          coalesce(round(100.0 * a.paye / nullif(a.total_du, 0), 1), 0)
           ) order by a.total_du desc, a.activite), '[]'::jsonb)
      into v_lignes
      from agg a;

    v_colonnes := jsonb_build_array(
      jsonb_build_object('cle', 'activite',       'libelle', 'Activité',       'type', 'texte'),
      jsonb_build_object('cle', 'nb_entreprises', 'libelle', 'Entreprises',    'type', 'nombre'),
      jsonb_build_object('cle', 'montant_total',  'libelle', 'Montant dû',     'type', 'montant'),
      jsonb_build_object('cle', 'montant_paye',   'libelle', 'Encaissé',       'type', 'montant'),
      jsonb_build_object('cle', 'solde',          'libelle', 'Solde restant',  'type', 'montant'),
      jsonb_build_object('cle', 'taux',           'libelle', 'Recouvrement',   'type', 'pourcentage')
    );

    select count(*), coalesce(sum(e.montant_total_du), 0), coalesce(sum(e.montant_deja_paye), 0)
      into v_nb, v_total, v_paye
      from public.entreprises e;

    v_totaux := jsonb_build_object(
      'nb_entreprises', v_nb,
      'montant_total',  v_total,
      'montant_paye',   v_paye,
      'solde',          greatest(v_total - v_paye, 0)
    );
    v_resume := jsonb_build_array(
      jsonb_build_object('libelle', 'Entreprises', 'valeur', v_nb,                          'type', 'nombre'),
      jsonb_build_object('libelle', 'Montant dû',  'valeur', v_total,                       'type', 'montant'),
      jsonb_build_object('libelle', 'Encaissé',    'valeur', v_paye,                        'type', 'montant'),
      jsonb_build_object('libelle', 'Solde',       'valeur', greatest(v_total - v_paye, 0), 'type', 'montant')
    );

  -- ========================================================= nouveaux_comptes
  when 'nouveaux_comptes' then
    v_groupe := coalesce(nullif(lower(btrim(coalesce(v_filtres->>'groupe', ''))), ''), 'jour');
    if v_groupe not in ('jour', 'semaine', 'mois') then
      raise exception 'GROUPE_INVALIDE|Regroupement inconnu : « jour », « semaine » ou « mois ».';
    end if;

    v_titre := 'Nouveaux comptes par période';
    v_parametres := jsonb_build_object('groupe', v_groupe);

    with e as (
      select date_trunc(v_groupe, e.created_at)::date as p, count(*) as nb
        from public.entreprises e
       where e.created_at >= v_d0 and e.created_at < v_d1
       group by 1
    ),
    u as (
      select date_trunc(v_groupe, u.created_at)::date as p, count(*) as nb
        from public.utilisateurs u
       where u.created_at >= v_d0 and u.created_at < v_d1
       group by 1
    ),
    t as (
      select p from e union select p from u
    )
    select coalesce(jsonb_agg(jsonb_build_object(
             'periode',        case when v_groupe = 'mois'
                                    then to_char(t.p, 'MM/YYYY')
                                    else to_char(t.p, 'DD/MM/YYYY') end,
             'nb_entreprises', coalesce((select e.nb from e where e.p = t.p), 0),
             'nb_utilisateurs', coalesce((select u.nb from u where u.p = t.p), 0)
           ) order by t.p), '[]'::jsonb)
      into v_lignes
      from t;

    v_colonnes := jsonb_build_array(
      jsonb_build_object('cle', 'periode',         'libelle', case when v_groupe = 'mois' then 'Mois' when v_groupe = 'semaine' then 'Semaine (début)' else 'Jour' end, 'type', 'texte'),
      jsonb_build_object('cle', 'nb_entreprises',  'libelle', 'Nouvelles entreprises', 'type', 'nombre'),
      jsonb_build_object('cle', 'nb_utilisateurs', 'libelle', 'Nouveaux utilisateurs', 'type', 'nombre')
    );

    select (select count(*) from public.entreprises e where e.created_at >= v_d0 and e.created_at < v_d1),
           (select count(*) from public.utilisateurs u where u.created_at >= v_d0 and u.created_at < v_d1)
      into v_nb, v_total;

    v_totaux := jsonb_build_object('nb_entreprises', v_nb, 'nb_utilisateurs', v_total);
    v_resume := jsonb_build_array(
      jsonb_build_object('libelle', 'Nouvelles entreprises',  'valeur', v_nb,    'type', 'nombre'),
      jsonb_build_object('libelle', 'Nouveaux utilisateurs',  'valeur', v_total, 'type', 'nombre')
    );

  else
    raise exception 'TYPE_INVALIDE|Type de rapport plateforme inconnu : « % ».', v_type;
  end case;

  return public.rapport_enveloppe(
    v_type, v_titre, 'plateforme',
    v_debut, v_fin,
    v_colonnes, v_lignes, v_totaux, v_resume, v_parametres
  );
end;
$$;

