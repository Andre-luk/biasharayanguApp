-- ============================================================================
--  5. TRAÇABILITÉ — `rpc_rapport_tracer` & `rpc_rapports_historique`
-- ============================================================================

-- 5.a `rpc_rapport_tracer` -----------------------------------------------------
--  Appelée par l'application à CHAQUE génération (format 'apercu') et à
--  chaque export ('pdf', 'excel', 'partage', 'impression'). Insère :
--    • une ligne dans `rapports_generes` (référence + empreinte SHA-256) ;
--    • une trace `journal_audit` (action 'RAPPORT').
--  Codes : SESSION_ABSENTE | ACCES_REFUSE | DROIT_REFUSE | FORMAT_INVALIDE |
--          PORTEE_INVALIDE

create or replace function public.rpc_rapport_tracer(
  p_portee     text,
  p_type       text,
  p_debut      date default null,
  p_fin        date default null,
  p_format     text default 'apercu',
  p_reference  text default null,
  p_empreinte  text default null,
  p_parametres jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user      uuid := auth.uid();
  v_owner     uuid;
  v_portee    text := lower(btrim(coalesce(p_portee, 'entreprise')));
  v_type      text := btrim(coalesce(p_type, ''));
  v_format    text := lower(btrim(coalesce(p_format, 'apercu')));
  v_reference text;
  v_empreinte text := nullif(btrim(coalesce(p_empreinte, '')), '');
  v_rapport   record;
begin
  if v_user is null then
    raise exception 'SESSION_ABSENTE|Connectez-vous pour enregistrer un rapport.';
  end if;

  if v_portee not in ('entreprise', 'plateforme') then
    raise exception 'PORTEE_INVALIDE|Portée inconnue : « entreprise » ou « plateforme ».';
  end if;

  if v_format not in ('apercu', 'pdf', 'excel', 'partage', 'impression') then
    raise exception 'FORMAT_INVALIDE|Format d''export inconnu : apercu, pdf, excel, partage ou impression.';
  end if;

  if length(v_type) < 2 then
    raise exception 'TYPE_INVALIDE|Type de rapport manquant.';
  end if;

  if v_portee = 'plateforme' then
    if not public.est_plateforme() then
      raise exception 'ACCES_REFUSE|Seul le personnel de la plateforme trace ces rapports.';
    end if;
    if not (public.peut('rapports', 'voir') or public.peut('finance', 'voir')
            or public.peut('paiements', 'voir') or public.peut('abonnements', 'voir')
            or public.peut('entreprises', 'voir')) then
      raise exception 'DROIT_REFUSE|Votre rôle ne permet pas de générer ces rapports.';
    end if;
    v_owner := null;
  else
    if public.finance_role_plateforme_bloque() then
      raise exception 'ACCES_REFUSE|La finance d''une entreprise est privée : le personnel de la plateforme n''y a pas accès.';
    end if;

    v_owner := public.mon_proprietaire();
    if v_owner is null then
      v_owner := v_user;
    end if;

    if not public.acces_finance_entreprise(v_owner) then
      raise exception 'ACCES_REFUSE|Vous n''êtes pas membre de cette entreprise.';
    end if;

    if not (public.peut('rapports', 'voir') or public.peut('caisse', 'voir')
            or public.peut('depenses', 'voir') or public.peut('stock', 'voir')
            or public.peut('finance', 'voir')) then
      raise exception 'DROIT_REFUSE|Votre rôle ne permet pas de générer ces rapports.';
    end if;
  end if;

  v_reference := nullif(btrim(coalesce(p_reference, '')), '');
  if v_reference is null then
    v_reference := 'RPT-' || to_char(now(), 'YYYYMMDD') || '-'
                || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
  end if;

  insert into public.rapports_generes (
    owner_id, utilisateur_id, type_rapport, portee,
    periode_debut, periode_fin, format, reference, empreinte, parametres, created_at
  ) values (
    v_owner, v_user, v_type, v_portee,
    p_debut, p_fin, v_format, v_reference, v_empreinte, coalesce(p_parametres, '{}'::jsonb), now()
  )
  returning id, created_at into v_rapport;

  insert into public.journal_audit (
    id, entreprise_id, action, utilisateur_id, details, created_at
  ) values (
    gen_random_uuid(), null, 'RAPPORT', v_user,
    jsonb_build_object(
      'rapport_id', v_rapport.id,
      'type',       v_type,
      'portee',     v_portee,
      'format',     v_format,
      'debut',      p_debut,
      'fin',        p_fin,
      'reference',  v_reference,
      'empreinte',  v_empreinte,
      'boutique',   v_owner
    ),
    now()
  );

  return jsonb_build_object(
    'rapport_id', v_rapport.id,
    'reference',  v_reference,
    'type',       v_type,
    'portee',     v_portee,
    'format',     v_format,
    'empreinte',  v_empreinte,
    'created_at', v_rapport.created_at
  );
end;
$$;

comment on function public.rpc_rapport_tracer(text, text, date, date, text, text, text, jsonb) is
  'Enregistre une génération/export de rapport (registre + journal d''audit) avec référence et empreinte.';

-- 5.b `rpc_rapports_historique` -------------------------------------------------
--  Derniers rapports générés par la session :
--    • personnel plateforme → rapports « plateforme » ;
--    • entreprise           → rapports de sa boutique.
--  Codes : SESSION_ABSENTE | ACCES_REFUSE

create or replace function public.rpc_rapports_historique(p_limit integer default 50)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user   uuid := auth.uid();
  v_owner  uuid;
  v_limit  integer := least(greatest(coalesce(p_limit, 50), 1), 200);
  v_lignes jsonb := '[]'::jsonb;
  v_nb     integer := 0;
begin
  if v_user is null then
    raise exception 'SESSION_ABSENTE|Connectez-vous pour consulter l''historique.';
  end if;

  if public.est_plateforme() then
    select coalesce(jsonb_agg(x order by x->>'created_at' desc), '[]'::jsonb), count(*)
      into v_lignes, v_nb
      from (
        select jsonb_build_object(
                 'id',           r.id,
                 'type_rapport', r.type_rapport,
                 'portee',       r.portee,
                 'format',       r.format,
                 'debut',        r.periode_debut,
                 'fin',          r.periode_fin,
                 'reference',    r.reference,
                 'empreinte',    r.empreinte,
                 'parametres',   r.parametres,
                 'created_at',   r.created_at,
                 'utilisateur',  coalesce(nullif(btrim(u.nom), ''), u.email, '')
               ) as x
          from public.rapports_generes r
          left join public.utilisateurs u on u.id = r.utilisateur_id
         where r.portee = 'plateforme'
         order by r.created_at desc
         limit v_limit
      ) s;
  else
    v_owner := public.mon_proprietaire();
    if v_owner is null then
      v_owner := v_user;
    end if;

    if not public.acces_finance_entreprise(v_owner) then
      raise exception 'ACCES_REFUSE|Vous n''êtes pas membre de cette entreprise.';
    end if;

    select coalesce(jsonb_agg(x order by x->>'created_at' desc), '[]'::jsonb), count(*)
      into v_lignes, v_nb
      from (
        select jsonb_build_object(
                 'id',           r.id,
                 'type_rapport', r.type_rapport,
                 'portee',       r.portee,
                 'format',       r.format,
                 'debut',        r.periode_debut,
                 'fin',          r.periode_fin,
                 'reference',    r.reference,
                 'empreinte',    r.empreinte,
                 'parametres',   r.parametres,
                 'created_at',   r.created_at,
                 'utilisateur',  coalesce(nullif(btrim(u.nom), ''), u.email, '')
               ) as x
          from public.rapports_generes r
          left join public.utilisateurs u on u.id = r.utilisateur_id
         where r.owner_id = v_owner
         order by r.created_at desc
         limit v_limit
      ) s;
  end if;

  return jsonb_build_object('lignes', v_lignes, 'nb', v_nb);
end;
$$;

comment on function public.rpc_rapports_historique(integer) is
  'Historique des rapports générés (boutique ou plateforme selon le rôle connecté).';


