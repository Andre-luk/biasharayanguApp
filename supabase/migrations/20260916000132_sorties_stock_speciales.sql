-- ============================================================================
--  biashara_yangu — MIGRATION 0132 : LES SORTIES DE STOCK SPÉCIALES
--
--  PROBLÈME RÉSOLU
--    Jusqu'ici, une marchandise ne pouvait quitter le stock que par une
--    VENTE. Or un stock diminue aussi pour d'autres raisons :
--
--      • le propriétaire consomme un article de sa propre boutique
--        (« j'ai consommé un sucré ») ;
--      • un article est offert / sert d'échantillon (« goffre ») ;
--      • une bouteille est cassée, un produit est périmé, un article est
--        perdu ou volé ;
--      • une marchandise est rendue au fournisseur ;
--      • un article sert à la fabrication interne (ingrédients d'un goffre).
--
--    Dans tous ces cas l'article SORT du stock mais AUCUN ARGENT n'entre en
--    caisse. Avant cette migration, la seule façon de faire baisser le stock
--    était un « ajustement d'inventaire » : il corrige bien la quantité, mais
--    il ne dit pas POURQUOI, ne valorise pas la perte et ne se présente pas
--    comme un document justificatif.
--
--  CE QUE FAIT CETTE MIGRATION
--    1. Table `public.sorties_stock` : une ligne = une sortie justifiée
--       (article, quantité, motif, note, valeur unitaire, date, auteur).
--    2. Trigger `trg_sorties_stock_appliquer` : décrémente
--       `produits.quantite` (même mécanisme que les ventes). ⚠️ AUCUN
--       mouvement de caisse n'est créé : une sortie n'est pas un encaissement.
--    3. `rpc_stock_sortie(...)` : enregistre une sortie, refuse un stock
--       insuffisant, valorise la perte, journalise (`SORTIE_STOCK`).
--    4. `rpc_stock_sorties_liste(...)` : historique filtrable (période,
--       article, motif) + totaux — c'est la source du RAPPORT IMPRIMABLE.
--
--  GARDE-FOUS
--    • le motif est OBLIGATOIRE et doit appartenir à la liste connue ;
--    • la quantité doit être > 0 et ne peut pas dépasser le stock réel ;
--    • l'article doit appartenir à la boutique de l'utilisateur ;
--    • l'opération est tracée dans `journal_audit` (qui, quoi, combien, quand).
--
--  OÙ L'EXÉCUTER
--    Supabase Dashboard → SQL Editor → New query → coller → Run
--
--  ⚠️ IDEMPOTENT : peut être relancé sans dupliquer ni détruire de données.
-- ============================================================================

