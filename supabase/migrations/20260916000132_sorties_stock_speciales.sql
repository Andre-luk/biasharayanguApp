-- ============================================================================
--  1. TABLE `sorties_stock` — UNE SORTIE JUSTIFIÉE
-- ============================================================================
--  `motif` est un CODE stable (l'application affiche le libellé français) :
--  les rapports et les totaux ne dépendent donc pas d'un texte libre.
--
--  `valeur_unitaire` fige le coût au moment de la sortie : si le prix d'achat
--  change demain, la perte d'hier reste juste (même logique que la facture,
--  qui ne se réécrit jamais).

create table if not exists public.sorties_stock (
  id             bigint generated by default as identity primary key,
  owner_id       uuid not null,
  produit_id     bigint not null,
  quantite       numeric not null,
  motif          text not null,
  note           text,
  valeur_unitaire numeric not null default 0,
  date           timestamptz not null default now(),
  utilisateur_id uuid,
  created_at     timestamptz not null default now()
);

comment on table public.sorties_stock is
  'Sorties de stock NON commerciales (consommation du propriétaire, offert, perte, casse, péremption, retour fournisseur…) : le stock diminue, la caisse NE bouge PAS.';

comment on column public.sorties_stock.motif is
  'Code du motif : consommation_proprietaire | offert | perte | casse | peremption | retour_fournisseur | usage_interne | autre.';

comment on column public.sorties_stock.valeur_unitaire is
  'Coût unitaire figé au moment de la sortie (prix d''achat de l''unité de base) : sert à valoriser la perte dans le rapport.';

create index if not exists idx_sorties_stock_owner_date
  on public.sorties_stock (owner_id, date desc);

create index if not exists idx_sorties_stock_produit
  on public.sorties_stock (produit_id, date desc);


-- ============================================================================
--  2. TRIGGER — LE STOCK DIMINUE, LA CAISSE NE BOUGE PAS
-- ============================================================================
--  Même principe que les ventes : la fonction n'écrit pas `produits.quantite`
--  depuis l'application, c'est la base qui applique le mouvement. Aucun
--  `insert` dans `caisse` n'est fait ici — et c'est volontaire : une sortie
--  n'est pas une vente, elle ne rapporte rien.

create or replace function public.sorties_stock_appliquer()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.produits
     set quantite = coalesce(quantite, 0) - new.quantite
   where id = new.produit_id;

  return new;
end;
$$;

comment on function public.sorties_stock_appliquer() is
  'Décrémente le stock de l''article sorti. N''écrit JAMAIS dans la caisse : une sortie spéciale ne rapporte pas d''argent.';

drop trigger if exists trg_sorties_stock_appliquer on public.sorties_stock;
create trigger trg_sorties_stock_appliquer
  after insert on public.sorties_stock
  for each row execute function public.sorties_stock_appliquer();


-- ============================================================================
--  3. `rpc_stock_sortie` — ENREGISTRER UNE SORTIE JUSTIFIÉE
-- ============================================================================
--  Signature :
--    p_produit_id     bigint  — article qui sort ;
--    p_quantite       numeric — quantité sortie, en UNITÉS DE BASE ;
--    p_motif          text    — code du motif (liste fermée) ;
--    p_note           text    — précision libre (facultative) ;
--    p_valeur_unitaire numeric — coût unitaire (défaut : prix d'achat) ;
--    p_date           timestamptz — défaut : maintenant.
--
--  Codes d'erreur : SESSION_ABSENTE | DROIT_REFUSE | PRODUIT_INTROUVABLE |
--                   HORS_BOUTIQUE | QUANTITE_INVALIDE | MOTIF_INVALIDE |
--                   STOCK_INSUFFISANT
--
--  ⚠️ Aucune ligne de `caisse`, aucune ligne de `ventes`, aucune ligne de
--     `paiements_dette` n'est écrite : le chiffre d'affaires est intact.

create or replace function public.rpc_stock_sortie(
  p_produit_id      bigint,
  p_quantite        numeric,
  p_motif           text,
  p_note            text default null,
  p_valeur_unitaire numeric default null,
  p_date            timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user    uuid := auth.uid();
  v_owner   uuid;
  v_motif   text := lower(btrim(coalesce(p_motif, '')));
  v_note    text := nullif(btrim(coalesce(p_note, '')), '');
  v_date    timestamptz := coalesce(p_date, now());
  v_produit record;
  v_valeur  numeric;
  v_avant   numeric;
  v_apres   numeric;
  v_ligne   bigint;
begin
  if v_user is null then
    raise exception 'SESSION_ABSENTE|Connectez-vous pour enregistrer une sortie de stock.';
  end if;

  if not (public.peut('stock', 'modifier') or public.est_plateforme()) then
    raise exception 'DROIT_REFUSE|Votre rôle ne permet pas d''enregistrer une sortie de stock.';
  end if;

  if p_quantite is null or p_quantite <= 0 then
    raise exception 'QUANTITE_INVALIDE|La quantité sortie doit être supérieure à zéro.';
  end if;

  if v_motif not in (
    'consommation_proprietaire', 'offert', 'perte', 'casse',
    'peremption', 'retour_fournisseur', 'usage_interne', 'autre'
  ) then
    raise exception 'MOTIF_INVALIDE|Choisissez le motif de la sortie (consommation, offert, perte, casse, péremption, retour fournisseur, usage interne ou autre).';
  end if;

  if p_valeur_unitaire is not null and p_valeur_unitaire < 0 then
    raise exception 'QUANTITE_INVALIDE|La valeur unitaire ne peut pas être négative.';
  end if;

  v_owner := public.mon_proprietaire();
  if v_owner is null then
    v_owner := v_user;
  end if;

  select p.id, p.nom, p.owner_id, coalesce(p.quantite, 0) as quantite,
         coalesce(p.prix_achat, 0) as prix_achat, p.unite_mesure
    into v_produit
    from public.produits p
   where p.id = p_produit_id
     for update;

  if not found then
    raise exception 'PRODUIT_INTROUVABLE|Article n° % introuvable : il a peut-être été supprimé.', p_produit_id;
  end if;

  if v_produit.owner_id is distinct from v_owner
     and not public.est_plateforme() then
    raise exception 'HORS_BOUTIQUE|L''article % n''appartient pas à votre boutique.', v_produit.nom;
  end if;

  v_avant := v_produit.quantite;

  if p_quantite > v_avant + 0.000001 then
    raise exception 'STOCK_INSUFFISANT|Il ne reste que % % de « % » en stock.', round(v_avant, 2), coalesce(v_produit.unite_mesure, 'unité'), v_produit.nom;
  end if;

  v_valeur := coalesce(p_valeur_unitaire, v_produit.prix_achat, 0);

  -- Le trigger `trg_sorties_stock_appliquer` retire la quantité du stock.
  insert into public.sorties_stock (
    owner_id, produit_id, quantite, motif, note, valeur_unitaire, date, utilisateur_id
  ) values (
    v_owner, p_produit_id, p_quantite, v_motif, v_note, v_valeur, v_date, v_user
  )
  returning id into v_ligne;

  select coalesce(p.quantite, 0)
    into v_apres
    from public.produits p
   where p.id = p_produit_id;

  insert into public.journal_audit (
    id, entreprise_id, action, utilisateur_id, details, created_at
  ) values (
    gen_random_uuid(), null, 'SORTIE_STOCK', v_user,
    jsonb_build_object(
      'sortie_id',     v_ligne,
      'produit_id',    p_produit_id,
      'produit',       v_produit.nom,
      'quantite',      p_quantite,
      'unite',         v_produit.unite_mesure,
      'motif',         v_motif,
      'note',          v_note,
      'valeur_unitaire', v_valeur,
      'valeur_totale', round(p_quantite * v_valeur, 2),
      'stock_avant',   v_avant,
      'stock_apres',   v_apres,
      'caisse_impactee', false,
      'boutique',      v_owner
    ),
    now()
  );

  return jsonb_build_object(
    'sortie_id',      v_ligne,
    'produit_id',     p_produit_id,
    'nom',            v_produit.nom,
    'unite',          v_produit.unite_mesure,
    'quantite',       p_quantite,
    'motif',          v_motif,
    'note',           v_note,
    'valeur_unitaire', v_valeur,
    'valeur_totale',  round(p_quantite * v_valeur, 2),
    'date',           v_date,
    'stock_avant',    v_avant,
    'stock_apres',    v_apres,
    'caisse_impactee', false
  );
end;
$$;

comment on function public.rpc_stock_sortie(bigint, numeric, text, text, numeric, timestamptz) is
  'Enregistre une sortie de stock non commerciale (motif obligatoire) : le stock diminue, la caisse n''est PAS créditée.';


-- ============================================================================
--  4. `rpc_stock_sorties_liste` — HISTORIQUE ET TOTAUX (RAPPORT)
-- ============================================================================
--  Signature :
--    p_debut      date   — défaut : premier jour du mois courant ;
--    p_fin        date   — défaut : aujourd'hui (INCLUS) ;
--    p_produit_id bigint — facultatif : un seul article ;
--    p_motif      text   — facultatif : un seul motif.
--
--  Retourne :
--    • `lignes`  — chaque sortie (article, quantité, unité, motif, note,
--                  valeur, date, auteur) ;
--    • `totaux`  — nombre de sorties, valeur totale, et le détail PAR MOTIF
--                  (c'est ce que le rapport imprimé met en avant : combien
--                  a coûté la casse, combien la consommation du patron…).
--
--  Codes d'erreur : SESSION_ABSENTE | ACCES_REFUSE | DROIT_REFUSE | DATE_INVALIDE

create or replace function public.rpc_stock_sorties_liste(
  p_debut      date default null,
  p_fin        date default null,
  p_produit_id bigint default null,
  p_motif      text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user   uuid := auth.uid();
  v_owner  uuid;
  v_debut  date := coalesce(p_debut, date_trunc('month', current_date)::date);
  v_fin    date := coalesce(p_fin, current_date);
  v_motif  text := nullif(lower(btrim(coalesce(p_motif, ''))), '');
  v_d0     timestamptz;
  v_d1     timestamptz;
  v_lignes jsonb := '[]'::jsonb;
  v_par_motif jsonb := '{}'::jsonb;
  v_nb     integer := 0;
  v_total  numeric := 0;
begin
  if v_user is null then
    raise exception 'SESSION_ABSENTE|Connectez-vous pour consulter les sorties de stock.';
  end if;

  v_owner := public.mon_proprietaire();
  if v_owner is null then
    v_owner := v_user;
  end if;

  if not public.acces_finance_entreprise(v_owner) then
    raise exception 'ACCES_REFUSE|Vous n''êtes pas membre de cette entreprise.';
  end if;

  if not (public.peut('stock', 'voir') or public.est_plateforme()) then
    raise exception 'DROIT_REFUSE|Votre rôle ne permet pas de consulter les sorties de stock.';
  end if;

  if v_fin < v_debut then
    raise exception 'DATE_INVALIDE|La date de fin ne peut pas précéder la date de début.';
  end if;

  v_d0 := v_debut::timestamptz;
  v_d1 := (v_fin + 1)::timestamptz;

  select coalesce(jsonb_agg(l.objet order by l.quand desc, l.sortie_id desc), '[]'::jsonb)
    into v_lignes
    from (
      select s.id as sortie_id,
             s.date as quand,
             jsonb_build_object(
               'sortie_id',      s.id,
               'produit_id',     s.produit_id,
               'produit',        coalesce(p.nom, 'Article supprimé'),
               'unite',          coalesce(p.unite_mesure, 'unité'),
               'quantite',       s.quantite,
               'motif',          s.motif,
               'note',           s.note,
               'valeur_unitaire', s.valeur_unitaire,
               'valeur_totale',  round(s.quantite * coalesce(s.valeur_unitaire, 0), 2),
               'date',           s.date
             ) as objet
        from public.sorties_stock s
        left join public.produits p on p.id = s.produit_id
       where s.owner_id = v_owner
         and s.date >= v_d0 and s.date < v_d1
         and (p_produit_id is null or s.produit_id = p_produit_id)
         and (v_motif is null or s.motif = v_motif)
    ) l;

  select count(*),
         coalesce(sum(s.quantite * coalesce(s.valeur_unitaire, 0)), 0)
    into v_nb, v_total
    from public.sorties_stock s
   where s.owner_id = v_owner
     and s.date >= v_d0 and s.date < v_d1
     and (p_produit_id is null or s.produit_id = p_produit_id)
     and (v_motif is null or s.motif = v_motif);

  select coalesce(jsonb_object_agg(motif, jsonb_build_object(
           'nb',    nb,
           'valeur', valeur
         )), '{}'::jsonb)
    into v_par_motif
    from (
      select s.motif as motif,
             count(*) as nb,
             round(sum(s.quantite * coalesce(s.valeur_unitaire, 0)), 2) as valeur
        from public.sorties_stock s
       where s.owner_id = v_owner
         and s.date >= v_d0 and s.date < v_d1
         and (p_produit_id is null or s.produit_id = p_produit_id)
         and (v_motif is null or s.motif = v_motif)
       group by s.motif
    ) g;

  return jsonb_build_object(
    'debut',      v_debut,
    'fin',        v_fin,
    'lignes',     v_lignes,
    'totaux', jsonb_build_object(
      'nb',        v_nb,
      'valeur',    round(v_total, 2),
      'par_motif', v_par_motif
    )
  );
end;
$$;

comment on function public.rpc_stock_sorties_liste(date, date, bigint, text) is
  'Historique des sorties de stock non commerciales sur une période, avec totaux et détail par motif (source du rapport imprimable).';


