do $$
begin
  execute 'drop policy if exists m9_sorties_lecture on public.sorties_stock';
  execute 'create policy m9_sorties_lecture on public.sorties_stock
             for select to authenticated
             using (
               owner_id = auth.uid()
               or owner_id = public.mon_proprietaire()
               or public.est_plateforme()
             )';

  -- L'insertion directe reste possible pour la synchronisation hors ligne
  -- (même tolérance que les autres tables de mouvements).
  execute 'drop policy if exists m9_sorties_insertion on public.sorties_stock';
  execute 'create policy m9_sorties_insertion on public.sorties_stock
             for insert to authenticated
             with check (
               owner_id = auth.uid()
               or owner_id = public.mon_proprietaire()
               or public.est_plateforme()
             )';
end $$;


