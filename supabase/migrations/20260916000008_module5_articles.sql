-- ============================================================================
--  biashara_yangu — MODULE 5 : GESTION DES ARTICLES (MULTI-CONDITIONNEMENTS)
--
--  Un ARTICLE (table `public.produits`) est vendu :
--    • à l'unité de base            → « bouteille », « pièce », « kg »…
--    • par CONDITIONNEMENTS         → « Farde de 12 », « Carton de 24 »…
--      (table `public.conditionnements`, un QR code par emballage)
--
--  Ce script ALIGNE le schéma existant sur le cahier des charges Module 5 :
--
--    1. `public.categories`       — référentiel des catégories (nom unique)
--    2. `public.produits`         — colonne `description` + index de lecture
--    3. `public.conditionnements` — QR auto, cascade, contraintes
--    4. `updated_at` automatique sur les articles
--    5. RLS : chaque boutique ne voit QUE ses articles (+ collaborateurs)
--    6. Vérifications
--
--  OÙ L'EXÉCUTER
--    Supabase Dashboard → SQL Editor → New query → coller → Run
--
--  PRÉ-REQUIS
--    Module 4 déjà exécuté (`20260916000006_module4_permissions.sql`) :
--    ce script réutilise `public.peut(...)` et `public.est_plateforme()`
--    pour accorder l'écriture selon la matrice des rôles.
--
--  ⚠️ IDEMPOTENT : peut être relancé sans dupliquer ni détruire de données.
--     Les policies des trois tables sont REMPLACÉES par celles du Module 5.
-- ============================================================================


select set_config('search_path', 'public, extensions', true);

-- Contrôle préalable : le Module 4 doit être en place.
do $$
begin
  if not exists (
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where p.proname = 'peut' and n.nspname = 'public'
  ) or not exists (
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where p.proname = 'est_plateforme' and n.nspname = 'public'
  ) then
    raise exception
      'Module 4 absent : exécutez d''abord 20260916000006_module4_permissions.sql.';
  end if;
end $$;


-- ============================================================================
--  1. TABLE `public.categories` — RÉFÉRENTIEL DES CATÉGORIES
-- ============================================================================
--  Structure attendue : id (bigint), nom (unique).
--  La table peut déjà exister (créée à la main) : on la complète au lieu de
--  la remplacer.

create table if not exists public.categories (
  id  bigint generated by default as identity primary key,
  nom text not null
);

-- Identifiant auto si la table existante ne l'a pas encore.
create sequence if not exists public.categories_id_seq;

do $$
begin
  if (select column_default from information_schema.columns
       where table_schema = 'public' and table_name = 'categories'
         and column_name = 'id') is null
     and (select is_identity from information_schema.columns
           where table_schema = 'public' and table_name = 'categories'
             and column_name = 'id') = 'NO'
  then
    alter table public.categories
      alter column id set default nextval('public.categories_id_seq');
    alter sequence public.categories_id_seq owned by public.categories.id;
    raise notice 'categories.id : identifiant automatique branché.';
  end if;
end $$;

-- Un nom de catégorie est unique (insensible à la casse et aux espaces).
create unique index if not exists idx_categories_nom_unique
  on public.categories (lower(btrim(nom)));


-- ============================================================================
--  2. TABLE `public.produits` — L'ARTICLE DE BASE
-- ============================================================================
--  Colonnes du cahier des charges :
--    id, nom, categorie, prix_achat, prix_vente, quantite, unite_mesure,
--    photo, owner_id, created_at, updated_at — plus `description` (formulaire).

create table if not exists public.produits (
  id           bigint generated by default as identity primary key,
  nom          text not null,
  categorie    text default '',
  prix_achat   real default 0,
  prix_vente   real default 0,
  quantite     real default 0,          -- stock en UNITÉS DE BASE
  unite_mesure text default 'unité',
  photo        text,
  description  text,
  owner_id     uuid,                    -- propriétaire (le patron de la boutique)
  created_at   timestamptz default now(),
  updated_at   timestamptz default now()
);

-- Colonnes ajoutées aux tables existantes.
alter table public.produits add column if not exists description text;
alter table public.produits add column if not exists photo       text;

alter table public.produits alter column created_at set default now();
alter table public.produits alter column updated_at set default now();

-- Lectures de la liste des articles (filtre owner_id + tri par nom).
create index if not exists idx_produits_owner_id on public.produits (owner_id);
create index if not exists idx_produits_nom      on public.produits (lower(btrim(nom)));

comment on column public.produits.quantite is
  'Stock disponible exprimé en UNITÉS DE BASE (ex. bouteilles).';
comment on column public.produits.unite_mesure is
  'Unité de base de l''article (bouteille, pièce, kg…).';
comment on column public.produits.description is
  'Description libre de l''article (Module 5, champ optionnel).';


-- ============================================================================
--  3. TABLE `public.conditionnements` — LES EMBALLAGES VENDABLES
-- ============================================================================
--  Exemple : article « Eau Casino » (bouteille, 1000 CDF)
--    • Farde de 12  → 12 unités de base, 12000 CDF
--    • Carton de 24 → 24 unités de base, 24000 CDF
--
--  Le prix du conditionnement est INDÉPENDANT de (prix base × quantité) :
--  c'est précisément l'intérêt commercial des emballages.
--  `qr_code_id` est généré AUTOMATIQUEMENT par la base à la création.

create table if not exists public.conditionnements (
  id                   uuid primary key default gen_random_uuid(),
  produit_id           bigint not null,   -- lien obligatoire vers l'article
  libelle              text not null,     -- « Farde de 12 », « Carton de 24 »
  quantite_unites_base real not null,     -- 12, 24…
  prix_vente           real not null default 0,
  qr_code_id           uuid not null default gen_random_uuid(),
  code_barre_texte     text,              -- code-barre saisi (optionnel)
  created_at           timestamptz not null default now()
);

-- Colonnes / défauts des tables existantes.
alter table public.conditionnements alter column qr_code_id set default gen_random_uuid();
alter table public.conditionnements alter column created_at set default now();

-- Identifiant auto si la table existante ne l'a pas encore.
do $$
begin
  if (select column_default from information_schema.columns
       where table_schema = 'public' and table_name = 'conditionnements'
         and column_name = 'id') is null
     and (select is_identity from information_schema.columns
           where table_schema = 'public' and table_name = 'conditionnements'
             and column_name = 'id') = 'NO'
  then
    alter table public.conditionnements
      alter column id set default gen_random_uuid();
    raise notice 'conditionnements.id : gen_random_uuid() branché.';
  end if;
end $$;

-- Colonnes obligatoires si la table existante les tolérait nulles.
do $$
begin
  if (select is_nullable from information_schema.columns
       where table_schema = 'public' and table_name = 'conditionnements'
         and column_name = 'produit_id') = 'YES' then
    alter table public.conditionnements alter column produit_id set not null;
  end if;

  if (select is_nullable from information_schema.columns
       where table_schema = 'public' and table_name = 'conditionnements'
         and column_name = 'libelle') = 'YES' then
    alter table public.conditionnements alter column libelle set not null;
  end if;
end $$;

-- `Un conditionnement ne peut exister sans produit` + suppression en cascade :
-- supprimer un article supprime tous ses conditionnements.
do $$
begin
  if not exists (
    select 1
      from pg_constraint c
      join pg_class t on t.oid = c.conrelid
      join pg_namespace n on n.oid = t.relnamespace
     where n.nspname = 'public'
       and t.relname = 'conditionnements'
       and c.contype = 'f'
       and c.confrelid = 'public.produits'::regclass
  ) then
    alter table public.conditionnements
      add constraint conditionnements_produit_id_fkey
      foreign key (produit_id) references public.produits (id)
      on delete cascade;
    raise notice 'Clé étrangère conditionnements → produits (cascade) installée.';
  end if;
end $$;

-- Une quantité d'emballage est toujours strictement positive.
do $$
begin
  if not exists (
    select 1 from pg_constraint
     where conname = 'conditionnements_quantite_positive'
       and conrelid = 'public.conditionnements'::regclass
  ) then
    alter table public.conditionnements
      add constraint conditionnements_quantite_positive
      check (quantite_unites_base > 0);
  end if;
end $$;

create index if not exists idx_conditionnements_produit_id
  on public.conditionnements (produit_id);
create unique index if not exists idx_conditionnements_qr_code
  on public.conditionnements (qr_code_id);

comment on column public.conditionnements.quantite_unites_base is
  'Nombre d''unités de base contenues dans un exemplaire du conditionnement.';
comment on column public.conditionnements.qr_code_id is
  'Identifiant unique encodé dans le QR code, généré automatiquement.';


-- ============================================================================
--  4. `updated_at` AUTOMATIQUE SUR LES ARTICLES
-- ============================================================================
--  La colonne est désormais maintenue par la base : plus aucune mise à jour
--  d'article ne peut l'oublier. (Le client peut toujours l'écrire, la base
--  réécrit la date exacte.)

create or replace function public.maj_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_produits_updated_at on public.produits;
create trigger trg_produits_updated_at
  before update on public.produits
  for each row
  execute function public.maj_updated_at();


-- ============================================================================
--  5. RLS — CHAQUE BOUTIQUE NE VOIT QUE SON CATALOGUE
-- ============================================================================
--  « Propriétaire courant » d'un utilisateur connecté :
--    • propriétaire d'une boutique → lui-même ;
--    • collaborateur (parent_id renseigné) → le patron dont il dépend.
--
--  Les règles ci-dessous REMPLACENT les anciennes policies des trois tables
--  (elles sont retirées une à une, quel que soit leur nom).
--
--  Rappel de la matrice Module 4 utilisée ici :
--    • écriture des articles   → action `articles` (creer / modifier / supprimer)
--    • rangement du stock      → action `stock`    (supprimer aussi, pour la
--      suppression d'un article depuis l'écran Stock)
--    • staff La Perle          → lecture de tous les catalogues.

create or replace function public.mon_proprietaire()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(u.parent_id, u.id)
    from public.utilisateurs u
   where u.id = auth.uid();
$$;

comment on function public.mon_proprietaire() is
  'Identifiant du propriétaire (patron) dont dépend l''utilisateur connecté.';

-- Propriétaire d'un article, lu sans passer par la RLS de `produits`
-- (utilisé par les policies de `conditionnements`).
create or replace function public.produit_proprietaire(p_produit_id bigint)
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select p.owner_id from public.produits p where p.id = p_produit_id;
$$;

comment on function public.produit_proprietaire(bigint) is
  'Identifiant du propriétaire d''un article (pour les policies des conditionnements).';

-- ------------------------------------------------ remplacement des policies
do $$
declare
  r record;
begin
  for r in
    select policyname, tablename
      from pg_policies
     where schemaname = 'public'
       and tablename in ('produits', 'categories', 'conditionnements')
  loop
    execute format('drop policy if exists %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;

-- La RLS doit être active pour que les policies s'appliquent.
alter table public.produits       enable row level security;
alter table public.categories     enable row level security;
alter table public.conditionnements enable row level security;

-- ---------------------------------------------------------------- produits
-- Lecture : mes articles (+ ceux du patron pour un collaborateur) ; le
-- personnel La Perle garde une vue globale (support, statistiques).
create policy produits_lecture on public.produits
  for select to authenticated
  using (
    owner_id = auth.uid()
    or owner_id = public.mon_proprietaire()
    or public.est_plateforme()
  );

-- Création : chaque article appartient à la boutique de son auteur.
create policy produits_creation on public.produits
  for insert to authenticated
  with check (
    owner_id = auth.uid()
    or owner_id = public.mon_proprietaire()
  );

-- Modification : les articles de la boutique (prix protégés par le trigger
-- du Module 4 pour les rôles sans droit de modification).
create policy produits_modification on public.produits
  for update to authenticated
  using (
    owner_id = auth.uid()
    or owner_id = public.mon_proprietaire()
  )
  with check (
    owner_id = auth.uid()
    or owner_id = public.mon_proprietaire()
  );

-- Suppression : droit `articles.supprimer` (écran Articles) ou
-- `stock.supprimer` (écran Stock historique).
create policy produits_suppression on public.produits
  for delete to authenticated
  using (
    (owner_id = auth.uid() or owner_id = public.mon_proprietaire())
    and (public.peut('articles', 'supprimer')
         or public.peut('stock', 'supprimer'))
  );

-- -------------------------------------------------------------- categories
-- Les catégories sont communes à toutes les boutiques (référentiel global).
create policy categories_lecture on public.categories
  for select to authenticated
  using (true);

create policy categories_creation on public.categories
  for insert to authenticated
  with check (
    public.peut('articles', 'creer')
    or public.peut('articles', 'modifier')
    or public.est_plateforme()
  );

create policy categories_modification on public.categories
  for update to authenticated
  using (
    public.peut('articles', 'modifier')
    or public.est_plateforme()
  )
  with check (
    public.peut('articles', 'modifier')
    or public.est_plateforme()
  );

create policy categories_suppression on public.categories
  for delete to authenticated
  using (
    public.peut('articles', 'supprimer')
    or public.est_plateforme()
  );

-- ---------------------------------------------------------- conditionnements
-- Lecture : conditionnements des articles visibles (même règle que produits).
create policy conditionnements_lecture on public.conditionnements
  for select to authenticated
  using (
    public.produit_proprietaire(produit_id) = auth.uid()
    or public.produit_proprietaire(produit_id) = public.mon_proprietaire()
    or public.est_plateforme()
  );

-- Écriture : il faut le droit de gérer les articles ET que l'article soit
-- bien dans la boutique de l'utilisateur.
create policy conditionnements_creation on public.conditionnements
  for insert to authenticated
  with check (
    (public.produit_proprietaire(produit_id) = auth.uid()
     or public.produit_proprietaire(produit_id) = public.mon_proprietaire())
    and (public.peut('articles', 'creer')
         or public.peut('articles', 'modifier'))
  );

create policy conditionnements_modification on public.conditionnements
  for update to authenticated
  using (
    (public.produit_proprietaire(produit_id) = auth.uid()
     or public.produit_proprietaire(produit_id) = public.mon_proprietaire())
    and (public.peut('articles', 'creer')
         or public.peut('articles', 'modifier'))
  )
  with check (
    (public.produit_proprietaire(produit_id) = auth.uid()
     or public.produit_proprietaire(produit_id) = public.mon_proprietaire())
    and (public.peut('articles', 'creer')
         or public.peut('articles', 'modifier'))
  );

create policy conditionnements_suppression on public.conditionnements
  for delete to authenticated
  using (
    (public.produit_proprietaire(produit_id) = auth.uid()
     or public.produit_proprietaire(produit_id) = public.mon_proprietaire())
    and (public.peut('articles', 'supprimer')
         or public.peut('articles', 'modifier'))
  );


-- ============================================================================
--  5 bis. PHOTOS DES ARTICLES (SUPABASE STORAGE)
-- ============================================================================
--  Les photos sont déposées dans le bucket public « articles », sous un
--  dossier au nom de l'utilisateur qui téléverse :
--
--      articles/<auth.uid()>/<horodatage>.jpg
--
--  L'URL publique est ensuite stockée dans `produits.photo`.
--  (Téléverser ne remplace jamais une photo : on ajoute un fichier, l'ancien
--  reste orphelin — sans conséquence à cette échelle.)

insert into storage.buckets (id, name, public)
values ('articles', 'articles', true)
on conflict (id) do nothing;

drop policy if exists "articles_storage_lecture" on storage.objects;
create policy "articles_storage_lecture" on storage.objects
  for select to public
  using (bucket_id = 'articles');

drop policy if exists "articles_storage_ajout" on storage.objects;
create policy "articles_storage_ajout" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'articles'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "articles_storage_maj" on storage.objects;
create policy "articles_storage_maj" on storage.objects
  for update to authenticated
  using (
    bucket_id = 'articles'
    and (storage.foldername(name))[1] = auth.uid()::text
  )
  with check (
    bucket_id = 'articles'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "articles_storage_suppression" on storage.objects;
create policy "articles_storage_suppression" on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'articles'
    and (storage.foldername(name))[1] = auth.uid()::text
  );


-- ============================================================================
--  6. VÉRIFICATIONS
-- ============================================================================

-- 6.a Colonnes des trois tables
select table_name, column_name, data_type, is_nullable, column_default
  from information_schema.columns
 where table_schema = 'public'
   and table_name in ('produits', 'categories', 'conditionnements')
 order by table_name, ordinal_position;

-- 6.b Policies finales (doit lister 4 + 4 + 4 = 12 lignes)
select tablename, policyname, cmd
  from pg_policies
 where schemaname = 'public'
   and tablename in ('produits', 'categories', 'conditionnements')
 order by tablename, policyname;

-- 6.c Clé étrangère en cascade (confdeltype = 'c')
select conname,
       conrelid::regclass  as table_source,
       confrelid::regclass as table_cible,
       confdeltype         as suppression
  from pg_constraint
 where contype = 'f'
   and conrelid = 'public.conditionnements'::regclass;

-- 6.d Droits des rôles de la boutique (doit renvoyer true/false)
select
  public.a_permission('PROPRIETAIRE', 'articles', 'creer')     as patron_cree_article,
  public.a_permission('PROPRIETAIRE', 'articles', 'supprimer') as patron_supprime_article,
  public.a_permission('MAGASINIER',   'articles', 'modifier')  as magasinier_modifie_article,
  public.a_permission('VENDEUR',      'articles', 'creer')     as vendeur_cree_article;

-- 6.e Bucket des photos
select id, name, public from storage.buckets where id = 'articles';


